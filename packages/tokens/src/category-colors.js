/**
 * 所有组件分类的完整配色方案
 */
export const componentCategoryColors = {
    'ui-basic': uiBasicColors,
    'inputs': inputsColors,
    'navigation': navigationColors,
    'feedback': feedbackColors,
    'overlays': overlaysColors,
    'data-display': dataDisplayColors,
    'layout': layoutColors,
    'charts': chartsColors,
    'forms': formsColors,
    'utilities': utilitiesColors,
};
/**
 * 获取指定分类的颜色配置
 */
export function getCategoryColors(categoryId) {
    return componentCategoryColors[categoryId] || null;
}
/**
 * 获取所有可用的分类ID
 */
export function getCategoryIds() {
    return Object.keys(componentCategoryColors);
}
/**
 * 检查分类是否存在
 */
export function hasCategoryColors(categoryId) {
    return categoryId in componentCategoryColors;
}
// ============================================================================
// 类型守卫和验证
// ============================================================================
/**
 * 验证是否为有效的组件分类颜色配置
 */
export function isValidComponentCategoryColors(colors) {
    return (colors &&
        typeof colors.primary === 'string' &&
        typeof colors.secondary === 'string' &&
        typeof colors.accent === 'string' &&
        typeof colors.glow === 'string' &&
        typeof colors.gradient === 'string' &&
        typeof colors.hoverGradient === 'string' &&
        typeof colors.selectedGradient === 'string');
}
// ============================================================================
// 便捷访问器
// ============================================================================
/**
 * 获取指定分类的主色调
 */
export function getPrimaryColor(categoryId) {
    const colors = getCategoryColors(categoryId);
    return colors?.primary || null;
}
/**
 * 获取指定分类的渐变色
 */
export function getGradientColor(categoryId) {
    const colors = getCategoryColors(categoryId);
    return colors?.gradient || null;
}
/**
 * 获取指定分类的悬停渐变
 */
export function getHoverGradient(categoryId) {
    const colors = getCategoryColors(categoryId);
    return colors?.hoverGradient || null;
}
